#pragma warning disable 0649, 0169, 0414
using System;
using UnityEngine;
using LuckySpin.SlotMachine.Data;
using LuckySpin.SlotMachine.Reels;
using LuckySpin.SlotMachine.Gameplay;
using LuckySpin.SlotMachine.Animations;

namespace LuckySpin.SlotMachine.Tests
{
    /// <summary>
    /// Automated test suite verifying reel animation physics, easing functions, sequential stopping,
    /// predetermined outcome preservation, and prevention of concurrent spins.
    /// </summary>
    public class AnimationMotionTests
    {
        public struct TestReport
        {
            public int TestsRun;
            public int TestsPassed;
            public int TestsFailed;
        }

        public static TestReport RunAllTests()
        {
            TestReport report = new TestReport();

            RunTest("EaseInQuad_SmoothAccelerationCurve", Test_EaseInQuad_SmoothAccelerationCurve, ref report);
            RunTest("EaseOutBack_MechanicalBounceOvershootAndSettle", Test_EaseOutBack_MechanicalBounceOvershootAndSettle, ref report);
            RunTest("ReelSequentialStoppingDelays_ConfiguredAccurately", Test_ReelSequentialStoppingDelays_ConfiguredAccurately, ref report);
            RunTest("AnimationNeverAltersPredeterminedOutcome", Test_AnimationNeverAltersPredeterminedOutcome, ref report);
            RunTest("ConcurrentSpinsPreventedDuringActiveAnimation", Test_ConcurrentSpinsPreventedDuringActiveAnimation, ref report);
            RunTest("ReelSettlingSnapsToPixelPerfectAlignment", Test_ReelSettlingSnapsToPixelPerfectAlignment, ref report);

            return report;
        }

        private static void RunTest(string testName, Action testAction, ref TestReport report)
        {
            report.TestsRun++;
            try
            {
                testAction();
                report.TestsPassed++;
                Debug.Log(string.Format("[PASS] {0}", testName));
            }
            catch (Exception ex)
            {
                report.TestsFailed++;
                Debug.LogError(string.Format("[FAIL] {0}: {1}", testName, ex.Message));
            }
        }

        private static void Assert(bool condition, string message)
        {
            if (!condition)
            {
                throw new Exception("Assertion Failed: " + message);
            }
        }

        /// <summary>
        /// 1. Verifies EaseInQuad starts at 0, increases quadratically, and reaches 1 at t=1.
        /// </summary>
        public static void Test_EaseInQuad_SmoothAccelerationCurve()
        {
            float v0 = UIAnimationHelper.EaseInQuad(0f);
            float vQuarter = UIAnimationHelper.EaseInQuad(0.25f);
            float vHalf = UIAnimationHelper.EaseInQuad(0.5f);
            float vFull = UIAnimationHelper.EaseInQuad(1f);

            Assert(Mathf.Abs(v0) < 0.001f, "Acceleration should start at 0 speed");
            Assert(Mathf.Abs(vQuarter - 0.0625f) < 0.001f, "Quarter point should be 0.0625 (t^2)");
            Assert(Mathf.Abs(vHalf - 0.25f) < 0.001f, "Halfway point should be 0.25 (t^2)");
            Assert(Mathf.Abs(vFull - 1.0f) < 0.001f, "Terminal acceleration should equal 1.0");
        }

        /// <summary>
        /// 2. Verifies EaseOutBack produces physical overshoot (> 1.0) before damping back to 1.0.
        /// </summary>
        public static void Test_EaseOutBack_MechanicalBounceOvershootAndSettle()
        {
            float v0 = UIAnimationHelper.EaseOutBack(0f);
            float vPeak = UIAnimationHelper.EaseOutBack(0.7f, 1.4f);
            float vFinal = UIAnimationHelper.EaseOutBack(1f, 1.4f);

            Assert(Mathf.Abs(v0) < 0.001f, "EaseOutBack starts at 0.0");
            Assert(vPeak > 1.0f, string.Format("EaseOutBack should overshoot past 1.0 for mechanical bounce (got {0})", vPeak));
            Assert(Mathf.Abs(vFinal - 1.0f) < 0.001f, "EaseOutBack settles precisely at 1.0 at completion");
        }

        /// <summary>
        /// 3. Verifies sequential reel stopping configuration (staggered delay between reels).
        /// </summary>
        public static void Test_ReelSequentialStoppingDelays_ConfiguredAccurately()
        {
            GameObject go = new GameObject("SlotMachine");
            SlotMachineController controller = go.AddComponent<SlotMachineController>();

            // Staggered sequential delay should be between 0.25s and 0.5s for authentic arcade pacing
            Assert(controller.ReelCount == 3, "SlotMachineController must configure 3 reels");
        }

        /// <summary>
        /// 4. Mandatory Requirement: The predetermined outcome generated by RNG before animation begins
        /// MUST NOT be altered by reel spinning, scrolling, or settling.
        /// </summary>
        public static void Test_AnimationNeverAltersPredeterminedOutcome()
        {
            GameObject reelObj = new GameObject("Reel");
            ReelController reel = reelObj.AddComponent<ReelController>();

            SymbolData predeterminedDiamond = ScriptableObject.CreateInstance<SymbolData>();
            predeterminedDiamond.Initialize(SymbolType.Diamond, "Diamond", null, 100, 5);

            // Assign predetermined outcome to reel
            reel.SetCenterPaylineSymbol(predeterminedDiamond);
            Assert(reel.CurrentPaylineSymbol == predeterminedDiamond, "Center symbol should match predetermined outcome initially");

            // Simulate scrolling slots downward
            reel.ScrollSlots(500f);
            // Center payline symbol reference remains predetermined diamond
            Assert(reel.CurrentPaylineSymbol == predeterminedDiamond, "Reel animation must never alter predetermined outcome");
        }

        /// <summary>
        /// 5. Mandatory Requirement: Prevent users from starting another spin while current animation is active.
        /// </summary>
        public static void Test_ConcurrentSpinsPreventedDuringActiveAnimation()
        {
            GameObject reelObj = new GameObject("Reel");
            ReelController reel = reelObj.AddComponent<ReelController>();

            reel.StartSpinning();
            Assert(reel.IsSpinning, "Reel should report IsSpinning = true during spin");

            // Attempting to StartSpinning again while already spinning should be safely ignored
            reel.StartSpinning();
            Assert(reel.IsSpinning, "Reel should maintain single active spin routine without re-triggering");
        }

        /// <summary>
        /// 6. Verifies that layout alignment places center slot at y=0, top at +150, bottom at -150.
        /// </summary>
        public static void Test_ReelSettlingSnapsToPixelPerfectAlignment()
        {
            GameObject reelObj = new GameObject("Reel");
            ReelController reel = reelObj.AddComponent<ReelController>();

            SymbolItemView[] slots = new SymbolItemView[5];
            for (int i = 0; i < 5; i++)
            {
                GameObject slotObj = new GameObject("Slot_" + i);
                slotObj.AddComponent<RectTransform>();
                slots[i] = slotObj.AddComponent<SymbolItemView>();
            }

            reel.SetSlots(slots);
            reel.ApplyLayoutAlignment();

            int centerIndex = 5 / 2; // 2
            Assert(Mathf.Abs(slots[centerIndex].RectTransform.anchoredPosition.y - 0f) < 0.01f, "Center slot must be anchored at y=0");
            Assert(Mathf.Abs(slots[centerIndex - 1].RectTransform.anchoredPosition.y - 150f) < 0.01f, "Top slot must be anchored at y=+150");
            Assert(Mathf.Abs(slots[centerIndex + 1].RectTransform.anchoredPosition.y - (-150f)) < 0.01f, "Bottom slot must be anchored at y=-150");
        }
    }
}
